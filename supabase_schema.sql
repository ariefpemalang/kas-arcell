-- ========================================================
-- SKEMA DATABASE BUKU ARcell DI SUPABASE (POSTGRESQL)
-- ========================================================

-- 1. Tabel Kategori
create table if not exists public.categories (
    id bigint generated by default as identity primary key,
    name text not null,
    type text not null check (type in ('in', 'out')),
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    constraint unique_category_name_type unique (name, type)
);

-- 2. Tabel Transaksi Kas
create table if not exists public.transactions (
    id text primary key,
    date text not null,
    type text not null check (type in ('in', 'out')),
    category text not null,
    amount numeric not null,
    payment_method text default 'Tunai',
    notes text,
    created_at text not null
);

-- 3. Tabel Piutang (Pelanggan berhutang ke konter)
create table if not exists public.receivables (
    id text primary key,
    debtor_name text not null,
    phone text,
    amount numeric not null,
    paid_amount numeric default 0,
    due_date text,
    notes text,
    status text default 'unpaid',
    payments jsonb default '[]'::jsonb,
    created_at text not null
);

-- 4. Tabel Hutang (Konter berhutang ke agen / supplier)
create table if not exists public.debts (
    id text primary key,
    creditor_name text not null,
    phone text,
    amount numeric not null,
    paid_amount numeric default 0,
    due_date text,
    notes text,
    status text default 'unpaid',
    payments jsonb default '[]'::jsonb,
    created_at text not null
);

-- 5. Tabel Riwayat Sesi Toko (Buka/Tutup Kasir Harian)
create table if not exists public.daily_sessions (
    id text primary key,
    tanggal text not null,
    jam_buka text,
    jam_tutup text,
    saldo_awal numeric default 0,
    saldo_akhir numeric default 0,
    pengeluaran numeric default 0,
    pengeluaran_list jsonb default '[]'::jsonb,
    keuntungan numeric default 0,
    catatan text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 6. Tabel Sesi Kasir yang Sedang Aktif
create table if not exists public.active_session (
    id text primary key default 'current',
    data jsonb not null,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 7. Tabel Pengaturan Toko
create table if not exists public.settings (
    id text primary key default 'current',
    data jsonb not null,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- ========================================================
-- KEAMANAN (Row Level Security - RLS)
-- Memberikan akses baca & tulis untuk anon key aplikasi
-- ========================================================

alter table public.categories enable row level security;
alter table public.transactions enable row level security;
alter table public.receivables enable row level security;
alter table public.debts enable row level security;
alter table public.daily_sessions enable row level security;
alter table public.active_session enable row level security;
alter table public.settings enable row level security;

drop policy if exists "Allow all operations for anon" on public.categories;
create policy "Allow all operations for anon" on public.categories for all to anon using (true) with check (true);

drop policy if exists "Allow all operations for anon" on public.transactions;
create policy "Allow all operations for anon" on public.transactions for all to anon using (true) with check (true);

drop policy if exists "Allow all operations for anon" on public.receivables;
create policy "Allow all operations for anon" on public.receivables for all to anon using (true) with check (true);

drop policy if exists "Allow all operations for anon" on public.debts;
create policy "Allow all operations for anon" on public.debts for all to anon using (true) with check (true);

drop policy if exists "Allow all operations for anon" on public.daily_sessions;
create policy "Allow all operations for anon" on public.daily_sessions for all to anon using (true) with check (true);

drop policy if exists "Allow all operations for anon" on public.active_session;
create policy "Allow all operations for anon" on public.active_session for all to anon using (true) with check (true);

drop policy if exists "Allow all operations for anon" on public.settings;
create policy "Allow all operations for anon" on public.settings for all to anon using (true) with check (true);

